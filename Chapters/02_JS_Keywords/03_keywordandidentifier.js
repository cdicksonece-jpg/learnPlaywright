// assiging a value to a variable
// we can assign a value to a variable using three ways
let x = 10; // using let keyword
var y = 20; // using var keyword
const z = 30; // using const keyword    

//difference between let, var and const
// 1. let and const are block scoped, var is function scoped
// 2. let and var can be reassigned, const cannot be reassigned
// 3. let and const are hoisted, var is not hoisted

// let are the most commonly used keyword to declare a variable in JavaScript. It is block scoped and can be reassigned. It is hoisted but not initialized. It is recommended to use let instead of var or const unless you have a specific reason to use them.
